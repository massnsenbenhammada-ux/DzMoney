const tg = window.Telegram?.WebApp;
if (tg) { tg.ready(); tg.expand(); }

const state = { page: 'home', balance: { coin: 0, dzx: 0, dzp: 0 } };
const $ = (id) => document.getElementById(id);

function toast(message) {
  const el = $('toast'); el.textContent = message; el.classList.add('show');
  clearTimeout(toast.timer); toast.timer = setTimeout(() => el.classList.remove('show'), 2600);
}
function showPage(page) {
  state.page = page;
  document.querySelectorAll('.page').forEach(el => el.classList.toggle('active', el.dataset.page === page));
  document.querySelectorAll('.nav-item').forEach(el => el.classList.toggle('active', el.dataset.go === page));
  window.scrollTo({ top: 0, behavior: 'smooth' });
}
function format(value) { return new Intl.NumberFormat('en-US', { maximumFractionDigits: 4 }).format(Number(value || 0)); }
function renderBalances() {
  $('coinBalance').textContent = format(state.balance.coin);
  $('dzxBalance').textContent = format(state.balance.dzx);
  $('dzpBalance').textContent = format(state.balance.dzp);
  $('totalBalance').textContent = format(state.balance.dzx);
  $('walletBalance').textContent = format(state.balance.dzx);
}
async function api(path, options = {}) {
  const headers = { 'Content-Type': 'application/json', ...(options.headers || {}) };
  if (tg?.initData) headers['X-Telegram-Init-Data'] = tg.initData;
  const response = await fetch(path, { ...options, headers });
  const text = await response.text();
  let data; try { data = text ? JSON.parse(text) : {}; } catch { data = { raw: text }; }
  if (!response.ok) throw Object.assign(new Error(data.error || `Request failed: ${response.status}`), { status: response.status, data });
  return data;
}
async function loadHealth() {
  try { await api('/health'); document.querySelector('.status').innerHTML = '<i></i> Online'; }
  catch { document.querySelector('.status').innerHTML = '<i style="background:#ff8d8d"></i> Offline'; }
}
async function loadSquad() {
  try {
    const data = await api('/api/squad');
    const squad = data.squad || data;
    const active = squad.active_members ?? squad.activeMembers;
    const activity = squad.activity_percent ?? squad.activityPercent;
    if (active != null) $('activeMembers').textContent = format(active);
    if (activity != null) $('squadActivity').textContent = `${format(activity)}%`;
    const progress = Number(squad.goal_progress ?? squad.goalProgress ?? 0);
    $('goalProgress').style.width = `${Math.max(0, Math.min(100, progress))}%`;
    $('goalProgressText').textContent = `${format(progress)}% complete`;
  } catch {
    $('goalProgressText').textContent = 'Squad data will appear after authentication';
  }
}

document.addEventListener('click', (event) => {
  const nav = event.target.closest('[data-go]');
  if (nav) { showPage(nav.dataset.go); if (nav.dataset.go === 'squad') loadSquad(); return; }
  if (event.target.closest('#dailyBtn') || event.target.closest('#taskVerifyBtn')) {
    toast('Verification is handled by the server. The verification ad will be connected next.');
  }
  if (event.target.closest('#withdrawBtn')) toast('Withdrawal flow will open after wallet verification is connected.');
  if (event.target.closest('#copyReferral')) {
    const link = tg?.initDataUnsafe?.start_param ? tg.initDataUnsafe.start_param : '';
    const text = link ? `https://t.me/DzMoneyBot?start=${link}` : 'Referral link will be generated by the server.';
    navigator.clipboard?.writeText(text).then(() => toast('Referral link copied')).catch(() => toast(text));
  }
});

renderBalances();
loadHealth();
loadSquad();
